/**
 * Deterministic safety layer (pipeline stage 3, first line). Runs before and independently of
 * any model, so child-protection handling never depends on a model being available, correct or
 * un-jailbroken. The router model can raise the risk level; it can never lower what these rules
 * find.
 *
 * Patterns are English plus a small set of Afrikaans, isiXhosa and isiZulu terms.
 * TODO(content): native-speaker review and expansion of the non-English terms before launch.
 */
import type { RiskLevel } from './types';

const STRONG: RegExp[] = [
  /\b(sexual(ly)?\s+(abus|touch|assault)\w*|molest\w*|rap(e|ed|ing)|groom(ed|ing))\b/i,
  /\b(touch(es|ed|ing)?|fondl\w*)\b.{0,40}\b(private parts?|privates|genitals?|vagina|penis|bum|breasts?)\b/i,
  /\b(private parts?|privates)\b.{0,40}\b(touch|hurt|sore|bleed)\w*/i,
  /\b(abus(e|ed|ing|es)|assault(ed)?)\b.{0,40}\b(child|kid|boy|girl|him|her|learner|toddler|baby)\b/i,
  /\b(child|kid|boy|girl|learner|toddler|baby)\b.{0,40}\b(abus(e|ed|ing)|being hurt|beaten|burnt|burned)\b/i,
  /\b(whip(s|ped|ping)?|burn(s|ed|t)?|chok(e|ed|ing)|strangl\w*)\b.{0,30}\b(him|her|the child|my child|the baby)\b/i,
  /\bbeat(s|en|ing)?\s+(him|her|them|the child|my child)\s+up\b|\b(is|was|gets|got|being)\s+beaten\b/i,
  /\b(hit(s|ting)?|beat(s|ing)?)\b.{0,30}\b(with a|with an|with the)\b.{0,20}\b(belt|stick|sjambok|cable|wire|pipe|shoe)\b/i,
  /\b(someone|somebody|uncle|aunt|stepfather|stepmother|father|mother|dad|mom|mum|boyfriend|man|neighbou?r)\b.{0,40}\b(hurt(s|ing)?|touch(es|ing)?|hit(s|ting)?|beat(s|ing)?|slap(s|ping)?|kick(s|ing)?|punch(es|ing)?)\b.{0,20}\b(her|him|them|the child|the baby)\b/i,
  // Reported disclosures: "she told me he hits her", "he says his uncle beats him".
  /\b(told me|tells me|says|said)\b.{0,60}\b(hits?|hitting|beats?|beating|slaps?|slapping|kicks?|kicking|punch(es|ing)?|hurts?|hurting|touch(es|ing))\b.{0,20}\b(her|him|them|me)\b/i,
  // "Someone is hurting one of our toddlers", "they are abusing the children".
  /\b(someone|somebody|they|he|she|parents?|uncle|stepfather|boyfriend|neighbou?r)\b.{0,20}\b(hurting|abusing|harming)\b.{0,40}\b(child(ren)?|toddlers?|bab(y|ies)|learners?|kids?|boy|girl|him|her|them)\b/i,
  /\b(starv(ed|ing)|not (been )?fed for|left alone for days|locked (him|her|them) (in|up|out))\b/i,
  /\bscared to go home\b|\bdoesn'?t want to go home\b.{0,60}\b(hurt|hit|beat|touch|scared)\w*/i,
  // Afrikaans
  /\b(misbruik|molesteer|verkrag\w*|seksueel)\b/i,
  // isiXhosa / isiZulu (TODO(content): verify with native speakers)
  /\b(ukuxhatshazwa|uxhatshazwa|ukuhlukunyezwa|uhlukunyezwa|ukudlwengulwa|udlwengulwe)\b/i,
];

const WEAK: RegExp[] = [
  /\bbruis(e|es|ed|ing)\b/i,
  /\b(welts?|marks? on (his|her) (body|arms?|legs?|back))\b/i,
  /\bscared of (his|her) (father|mother|dad|mom|mum|uncle|stepfather)\b/i,
  /\b(neglect(ed)?|hungry every day|always hungry)\b/i,
  /\b(geslaan|slaan (hom|haar))\b/i,
];

const DIAGNOSIS: RegExp[] = [
  /\b(autis(m|tic)|asd|adhd|dyslexi\w*|dyspraxi\w*|cerebral palsy|fetal alcohol|fasd|down'?s? syndrome)\b/i,
  /\b(diagnos\w*|disorder|syndrome)\b/i,
  /\b(does|do|could|might)\s+(he|she|they|my child|the child|this child)\s+have\b/i,
  /\bis (he|she|my child|the child) (slow|delayed|normal|disabled|special needs)\b/i,
  /\b(developmental(ly)? delay(ed)?|speech delay)\b/i,
];

const INJECTION: RegExp[] = [
  /\bignore (all |any |your |the |previous |prior )+(instructions|rules|prompts?)\b/i,
  /\b(system prompt|developer mode|jailbreak|you are now|act as (an?|the) (unfiltered|uncensored))\b/i,
  /\b(reveal|print|show) (your|the) (instructions|prompt|rules)\b/i,
];

export interface SafetyFindings {
  risk: RiskLevel;
  childProtection: boolean;
  diagnosisRequest: boolean;
  injectionAttempt: boolean;
}

export function precheck(text: string): SafetyFindings {
  const childProtection = STRONG.some((r) => r.test(text));
  const weak = WEAK.some((r) => r.test(text));
  const diagnosisRequest = DIAGNOSIS.some((r) => r.test(text));
  const injectionAttempt = INJECTION.some((r) => r.test(text));
  const risk: RiskLevel = childProtection
    ? 'child_protection'
    : weak || diagnosisRequest
      ? 'sensitive'
      : 'normal';
  return { risk, childProtection, diagnosisRequest, injectionAttempt };
}

const ORDER: RiskLevel[] = ['normal', 'sensitive', 'child_protection'];

/** The higher of two risk levels. Models may raise risk, never lower it. */
export function maxRisk(a: RiskLevel, b: RiskLevel): RiskLevel {
  return ORDER.indexOf(a) >= ORDER.indexOf(b) ? a : b;
}

/**
 * The fixed child-protection response (CLAUDE.md §5). Never generated by a model, so it cannot
 * be talked out of or altered. Plain language, short steps.
 */
export function escalationMessage(opts: { safeguardingName?: string | null } = {}): string {
  const person = opts.safeguardingName
    ? `your centre’s child-protection person (${opts.safeguardingName})`
    : 'your centre’s child-protection person';
  return [
    'Thank you for telling me. What you describe could mean a child is not safe. Acting on it is the right thing to do.',
    '',
    '1. If the child is in danger right now, keep them with a safe adult and call the police on 10111.',
    `2. Tell ${person} today.`,
    '3. Report it to a social worker at your local Department of Social Development office, or call Childline on 116 (free, 24 hours).',
    '4. Write down what you saw or heard, in the child’s own words, with the date and time. Don’t question the child further and don’t confront anyone.',
    '',
    'I can’t give advice on a specific case, but you are not alone. Childline on 116 can guide you.',
  ].join('\n');
}

